#!/usr/bin/env python3
"""Stage and verify a color-only revision of the fifteen Figure 3--6 panels.

Figures 4/5 are regenerated by their current matplotlib source. Figures 3/6
retain their finalized vector paths: only RGB paint instructions are changed,
without rerunning dynamics or rewriting frozen experiment records.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

import pymupdf
from PIL import Image
from pypdf import PdfReader, PdfWriter
from pypdf.generic import ContentStream, FloatObject

from figure_palette import DEPTH_REPLACEMENTS, ROUTE_REPLACEMENTS

ROOT = Path(__file__).resolve().parents[1]
DIRECTORIES = ('fig03_depth_tradeoff', 'fig04_heldout_performance',
               'fig05_ablation_safety', 'fig06_representative_trajectory')
COLOR_OPERATORS = {b'rg', b'RG', b'g', b'G', b'k', b'K'}


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def svg_structure(path: Path) -> str:
    """Fingerprint geometry, text, dimensions and styles, excluding only color."""
    root = ET.parse(path).getroot()
    ids = {e.get('id'): f'node{i}' for i, e in enumerate(root.iter()) if e.get('id')}

    def normalize(value: str) -> str:
        for old, new in ids.items():
            value = value.replace(f'#{old})', f'#{new})')
            if value == f'#{old}':
                value = f'#{new}'
        return value

    def visit(element):
        tag = element.tag.split('}')[-1]
        if tag == 'metadata':
            return None
        attributes = {}
        for key, value in element.attrib.items():
            if key in ('fill', 'stroke', 'color') and re.fullmatch(r'#[0-9a-fA-F]{6}', value):
                continue
            if key == 'id':
                value = ids[value]
            elif key == 'style':
                parts = []
                for part in value.split(';'):
                    if not part.strip():
                        continue
                    name, setting = [v.strip() for v in part.split(':', 1)]
                    if name in ('fill', 'stroke', 'color') and re.fullmatch(r'#[0-9a-fA-F]{6}', setting):
                        continue
                    parts.append((name, normalize(setting)))
                value = repr(sorted(parts))
                if not parts:
                    continue
            attributes[key] = normalize(value)
        return [tag, sorted(attributes.items()), ' '.join((element.text or '').split()),
                [record for child in element if (record := visit(child)) is not None]]

    payload = json.dumps(visit(root), ensure_ascii=False).encode()
    return hashlib.sha256(payload).hexdigest()


def pdf_structure(path: Path) -> dict:
    """Retain every non-color drawing/text instruction and the page boxes."""
    reader = PdfReader(path)
    assert len(reader.pages) == 1, path
    page = reader.pages[0]
    streams = {}

    def collect(contents, resources, key):
        operations = ContentStream(contents, reader).operations
        payload = repr([(args, op) for args, op in operations if op not in COLOR_OPERATORS])
        streams[key] = hashlib.sha256(payload.encode()).hexdigest()
        if resources:
            for name, ref in resources.get('/XObject', {}).items():
                obj = ref.get_object()
                if obj.get('/Subtype') == '/Form':
                    collect(obj, obj.get('/Resources'), key + str(name))

    collect(page.get_contents(), page.get('/Resources'), 'page')
    # PDF serialization can round a box by sub-micro-point precision;
    # normalize only that representation, never the drawing coordinates.
    return {'media_box': [round(float(v), 5) for v in page.mediabox],
            'crop_box': [round(float(v), 5) for v in page.cropbox],
            'text': page.extract_text(), 'streams': streams}


def recolor_svg(source: Path, destination: Path, replacements: dict) -> None:
    text = source.read_text()
    text = re.sub(r'#[0-9a-fA-F]{6}', lambda m: replacements.get(m[0].lower(), m[0]), text)
    destination.write_text(text)
    assert svg_structure(source) == svg_structure(destination), source


def recolor_pdf(source: Path, destination: Path, replacements: dict) -> int:
    """Change RGB paint only; reject any change in non-color PDF instructions."""
    def rgb(value):
        return tuple(int(value[i:i+2], 16) / 255 for i in (1, 3, 5))

    mapping = [(rgb(old), rgb(new)) for old, new in replacements.items()]
    writer = PdfWriter(clone_from=source)
    changes = 0

    def change(contents):
        nonlocal changes
        stream = ContentStream(contents, writer)
        for args, operator in stream.operations:
            if operator in (b'rg', b'RG'):
                for old, new in mapping:
                    if max(abs(float(a)-b) for a, b in zip(args, old)) < 1e-8:
                        args[:] = [FloatObject(v) for v in new]
                        changes += 1
                        break
        return stream

    def forms(resources):
        if not resources:
            return
        for ref in resources.get('/XObject', {}).values():
            obj = ref.get_object()
            if obj.get('/Subtype') == '/Form':
                obj.set_data(change(obj).get_data())
                forms(obj.get('/Resources'))

    for page in writer.pages:
        page.replace_contents(change(page.get_contents()))
        forms(page.get('/Resources'))
    writer.write(destination)
    assert pdf_structure(source) == pdf_structure(destination), source
    return changes


def render_preview(pdf: Path, original_png: Path, destination: Path) -> None:
    """Render the new vector without distortion at the existing preview size."""
    with Image.open(original_png) as original:
        width, height = original.size
    with pymupdf.open(pdf) as document:
        page = document[0]
        scale = min(width / page.rect.width, height / page.rect.height)
        pixmap = page.get_pixmap(matrix=pymupdf.Matrix(scale, scale), alpha=False)
        rendered = Image.frombytes('RGB', (pixmap.width, pixmap.height), pixmap.samples)
    canvas = Image.new('RGB', (width, height), 'white')
    canvas.paste(rendered, ((width-rendered.width)//2, (height-rendered.height)//2))
    canvas.save(destination, dpi=(600, 600))


def protected_inputs() -> dict:
    files = [ROOT/'main.tex', ROOT/'references.bib']
    for directory in ('sections', 'tables', 'data', 'figures/fig01_framework',
                      'figures/fig02_rollout_example', 'figures/fig07_ros_camera_views'):
        files.extend(p for p in (ROOT/directory).rglob('*') if p.is_file())
    return {str(p.relative_to(ROOT)): sha(p) for p in sorted(files)}


def stage(destination: Path) -> dict:
    assert destination.resolve() != (ROOT/'figures').resolve()
    protected = protected_inputs()
    destination.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, str(ROOT/'scripts/generate_result_figures.py'),
                    '--output-root', str(destination)], check=True, capture_output=True, text=True)
    vector_records = []
    for directory, replacements in ((DIRECTORIES[0], DEPTH_REPLACEMENTS),
                                    (DIRECTORIES[3], ROUTE_REPLACEMENTS)):
        output = destination/directory
        output.mkdir(exist_ok=True)
        for source in sorted((ROOT/'figures'/directory).glob('*.svg')):
            recolor_svg(source, output/source.name, replacements)
            changes = recolor_pdf(source.with_suffix('.pdf'), output/source.with_suffix('.pdf').name, replacements)
            render_preview(output/source.with_suffix('.pdf').name, source.with_suffix('.png'),
                           output/source.with_suffix('.png').name)
            vector_records.append({'panel': source.stem, 'changed_pdf_color_commands': changes})
    reports = []
    for directory in DIRECTORIES:
        for source in sorted((ROOT/'figures'/directory).glob('*.svg')):
            result = destination/directory/source.name
            before, after = svg_structure(source), svg_structure(result)
            assert before == after, f'Non-color SVG content changed: {source.name}'
            old_pdf, new_pdf = pdf_structure(source.with_suffix('.pdf')), pdf_structure(result.with_suffix('.pdf'))
            for field in ('media_box', 'crop_box', 'text'):
                assert old_pdf[field] == new_pdf[field], f'PDF {field} changed: {source.name}'
            with Image.open(source.with_suffix('.png')) as old_png, Image.open(result.with_suffix('.png')) as new_png:
                assert old_png.size == new_png.size, source.name
                size = old_png.size
            reports.append({'panel': source.stem, 'noncolor_svg_sha256': before,
                            'pdf_box': new_pdf['media_box'], 'png_size': size,
                            'unchanged_geometry_text_and_dimensions': True})
        old_manifest = ROOT/'figures'/directory/'single_column_manifest.json'
        if old_manifest.exists():
            new_manifest = json.loads((destination/directory/old_manifest.name).read_text())
            assert json.loads(old_manifest.read_text())['evidence'] == new_manifest['evidence']
    assert len(reports) == 15
    assert protected == protected_inputs(), 'Protected manuscript/evidence changed'
    report = {'status': 'passed', 'revision': 'color-only', 'panels': reports,
              'vector_color_replacements': vector_records, 'protected_inputs': protected,
              'palette': {'depth': DEPTH_REPLACEMENTS, 'route': ROUTE_REPLACEMENTS},
              'source_script_sha256': sha(Path(__file__)),
              'palette_sha256': sha(ROOT/'scripts/figure_palette.py')}
    (destination/'palette_qa.json').write_text(json.dumps(report, indent=2)+'\n')
    return report


def apply_verified_stage(destination: Path) -> None:
    """Promote a visually reviewed stage, keeping recoverable pre-edit assets."""
    report = json.loads((destination/'palette_qa.json').read_text())
    assert report['status'] == 'passed' and report['protected_inputs'] == protected_inputs()
    for record in report['panels']:
        matches = list(destination.glob('*/'+record['panel']+'.svg'))
        assert len(matches) == 1 and svg_structure(matches[0]) == record['noncolor_svg_sha256']
    archive = ROOT/'archive/figure36_prepalette_20260908'
    archive.mkdir(exist_ok=False)
    shutil.copy2(ROOT/'figures/manifest.json', archive/'figure_manifest.json')
    for directory in DIRECTORIES:
        shutil.copytree(ROOT/'figures'/directory, archive/directory)
        for file in (destination/directory).iterdir():
            if file.is_file():
                shutil.copy2(file, ROOT/'figures'/directory/file.name)
    manifest_path = ROOT/'figures/manifest.json'
    manifest = json.loads(manifest_path.read_text())
    for figure in manifest['figures']:
        if figure['number'] in (3, 4, 5, 6):
            for record in figure['files']:
                record['sha256'] = sha(ROOT/record['file'])
    manifest_path.write_text(json.dumps(manifest, indent=2)+'\n')
    shutil.copy2(destination/'palette_qa.json', ROOT/'docs/FIGURE_PALETTE_QA_20260908.json')
    assert report['protected_inputs'] == protected_inputs()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-root', type=Path, default=ROOT/'build/palette_preview')
    parser.add_argument('--apply', action='store_true', help='Promote an existing visually reviewed stage')
    args = parser.parse_args()
    if args.apply:
        apply_verified_stage(args.output_root)
        print('Applied reviewed palette; original Figure 3--6 assets archived.')
    else:
        report = stage(args.output_root)
        print(json.dumps({'status': report['status'], 'panels': len(report['panels']),
                          'protected_files': len(report['protected_inputs'])}))


if __name__ == '__main__':
    main()
